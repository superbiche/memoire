-- schema/0011:10 — SQLite json_extract(meta_json,'$.k')=1 matches EXACTLY
-- a JSON boolean true (extracted as 1) or a numeric 1 — not the string
-- "1" (TEXT '1' = 1 is false under SQLite affinity). The jsonb-typed IN
-- ('true'::jsonb,'1'::jsonb) reproduces that exact width: -> preserves
-- JSON types, so string values do not match (round-1 finding 5 narrowed;
-- round-2 caught the ->> text form overshooting to strings). The query
-- side MUST use this same literal expression (0008/0011 lesson).
CREATE INDEX IF NOT EXISTS idx_events_redaction_violation
  ON events(id)
  WHERE (meta_json::jsonb -> 'redaction_contract_violation') IN ('true'::jsonb, '1'::jsonb);
