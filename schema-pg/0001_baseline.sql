-- Governance guards (schema/0007:35-49): AFTER-trigger RAISE(ABORT) with a
-- WHEN clause becomes a BEFORE trigger + RAISE EXCEPTION — same effect
-- (statement aborts, transaction rolls back), same condition, same message.
CREATE OR REPLACE FUNCTION governance_can_instruct_guard() RETURNS trigger AS $$
BEGIN
  IF NEW.can_instruct = 1 AND (NEW.provenance IS NULL OR NEW.provenance NOT IN ('user_confirmed','imported')) THEN
    RAISE EXCEPTION 'can_instruct requires provenance user_confirmed or imported';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS governance_observations_can_instruct_insert ON observations;
CREATE TRIGGER governance_observations_can_instruct_insert
  BEFORE INSERT ON observations
  FOR EACH ROW EXECUTE FUNCTION governance_can_instruct_guard();
DROP TRIGGER IF EXISTS governance_observations_can_instruct_update ON observations;
CREATE TRIGGER governance_observations_can_instruct_update
  BEFORE UPDATE ON observations
  FOR EACH ROW EXECUTE FUNCTION governance_can_instruct_guard();

